/**
 * Trạng thái các bài học Kanji đang được kích hoạt (mặc định chọn cả 11 bài)
 */
let selectedKanjiLessons = new Set();

/**
 * Lấy dữ liệu từ các bài học Kanji đã chọn
 */
function getSelectedKanjiLessonVocabData() {
    const combined = {};
    KANJI_LESSONS_CONFIG.forEach(lesson => {
        if (selectedKanjiLessons.has(lesson.id)) {
            const d = lesson.getData();
            if (d) Object.assign(combined, d);
        }
    });
    return combined;
}
