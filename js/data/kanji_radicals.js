/**
 * Tách phần Hán-Việt và Nghĩa từ key chuẩn Đông Du ("HƯU (Nghỉ ngơi)" -> { hanViet, meaning })
 */
function parseKanjiLabel(labelKey) {
    if (!labelKey) return { hanViet: '', meaning: '' };
    const m = labelKey.match(/^([^()]+?)\s*\((.+)\)\s*$/);
    if (m) {
        return { hanViet: m[1].trim(), meaning: m[2].trim() };
    }
    return { hanViet: labelKey.trim(), meaning: '' };
}

/**
 * Lấy thông tin tag bộ chữ của một ký tự Kanji
 */
function getKanjiRadicalTagInfo(kanjiChar) {
    if (!kanjiChar) return null;
    return KANJI_CHARACTER_TAGS[kanjiChar] || null;
}

