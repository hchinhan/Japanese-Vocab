let _cachedUnifiedKanjiCatalog = null;

/**
 * Tổng hợp danh mục Kanji N5 & N4 thống nhất (đã khử trùng giữa Trang 0 và Trang 1~9),
 * kèm đầy đủ nhãn, cấp độ, danh sách trang và tag bộ chữ.
 */
function buildUnifiedKanjiCatalog(forceRebuild = false) {
    if (_cachedUnifiedKanjiCatalog && !forceRebuild) {
        return _cachedUnifiedKanjiCatalog;
    }
    const byChar = new Map();

    const registerPage = (pageCfg, level) => {
        const data = pageCfg && pageCfg.getData ? pageCfg.getData() : null;
        if (!data) return;
        for (const [labelKey, kanjiChar] of Object.entries(data)) {
            const tags = KANJI_CHARACTER_TAGS[kanjiChar] || { primaryRadical: '', radicals: [] };
            const parsed = parseKanjiLabel(labelKey);
            const fallbackMeaning = KANJI_FALLBACK_MEANINGS[kanjiChar] || '';
            const resolvedMeaning = parsed.meaning || fallbackMeaning;
            const resolvedLabel = parsed.meaning
                ? labelKey
                : (fallbackMeaning ? `${parsed.hanViet} (${fallbackMeaning})` : labelKey);
            const isRadicalOnly = /^(BỘ |2 CHẤM|3 CHẤM|4 CHẤM|HAI CHẤM|NHÂN NÓN|NHI \()/i.test(labelKey);

            if (!byChar.has(kanjiChar)) {
                byChar.set(kanjiChar, {
                    char: kanjiChar,
                    label: resolvedLabel,
                    hanViet: parsed.hanViet,
                    meaning: resolvedMeaning,
                    level: level,
                    levels: [level],
                    pages: [{ id: pageCfg.id, shortName: pageCfg.shortName, title: pageCfg.title, level }],
                    primaryRadical: tags.primaryRadical,
                    radicals: Array.isArray(tags.radicals) ? tags.radicals.slice() : [],
                    isRadicalOnly
                });
            } else {
                const existing = byChar.get(kanjiChar);
                existing.pages.push({ id: pageCfg.id, shortName: pageCfg.shortName, title: pageCfg.title, level });
                if (!existing.levels.includes(level)) {
                    existing.levels.push(level);
                }
                // Ưu tiên nhãn đầy đủ có nghĩa trong ngoặc (từ Trang 1~9 / HT800 thay cho Trang 0)
                if (parsed.meaning && (!existing.meaning || existing.pages[0].id === 'kanji0')) {
                    existing.label = labelKey;
                    existing.hanViet = parsed.hanViet;
                    existing.meaning = parsed.meaning;
                }
                if (level === 'N5') {
                    existing.level = 'N5';
                }
            }
        }
    };

    if (typeof KANJI_PAGES_CONFIG !== 'undefined') {
        KANJI_PAGES_CONFIG.forEach(p => registerPage(p, 'N5'));
    }
    if (typeof KANJI_800_PAGES_CONFIG !== 'undefined') {
        KANJI_800_PAGES_CONFIG.forEach(p => registerPage(p, 'N4'));
    }

    _cachedUnifiedKanjiCatalog = Array.from(byChar.values());
    return _cachedUnifiedKanjiCatalog;
}

function getUnifiedKanjiCatalog() {
    return buildUnifiedKanjiCatalog(false);
}

/**
 * Lấy danh sách Kanji thuộc một Bộ chữ cụ thể
 * @param {string} radicalName - Tên chuẩn của bộ (VD: "Nhân đứng (亻)")
 * @param {object} opts - { includeComponents: true, level: 'all' | 'N5' | 'N4', includeRadicalEntry: true }
 */
function getKanjiByRadical(radicalName, opts = {}) {
    const {
        includeComponents = true,
        level = 'all',
        includeRadicalEntry = true
    } = opts;

    const catalog = getUnifiedKanjiCatalog();
    return catalog.filter(item => {
        if (!includeRadicalEntry && item.isRadicalOnly) return false;
        if (level !== 'all' && !item.levels.includes(level)) return false;
        if (includeComponents) {
            return item.radicals.includes(radicalName);
        }
        return item.primaryRadical === radicalName;
    });
}

/**
 * Thống kê danh sách chữ & số lượng N5/N4 cho tất cả các bộ trong một lượt duyệt
 */
function getRadicalItemsMap(opts = {}) {
    const {
        includeComponents = true,
        level = 'all',
        includeRadicalEntry = true
    } = opts;

    const map = new Map();
    KANJI_RADICALS_CONFIG.forEach(r => {
        map.set(r.name, { radical: r, items: [], n5Count: 0, n4Count: 0 });
    });

    const catalog = getUnifiedKanjiCatalog();
    catalog.forEach(item => {
        if (!includeRadicalEntry && item.isRadicalOnly) return;
        if (level !== 'all' && !item.levels.includes(level)) return;

        const targetTags = includeComponents ? item.radicals : [item.primaryRadical];
        targetTags.forEach(tag => {
            const bucket = map.get(tag);
            if (!bucket) return;
            bucket.items.push(item);
            if (item.levels.includes('N5')) bucket.n5Count++;
            if (item.levels.includes('N4') && !item.levels.includes('N5')) bucket.n4Count++;
        });
    });

    return map;
}

